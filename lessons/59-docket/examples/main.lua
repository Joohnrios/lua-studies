package.path = "./projects/lua-rpg-core/?.lua;" .. package.path

local Player = require("player")
local Creature = require("creature")
local Watch = require("watch")
local Battle = require("battle")
local Strike = require("strike")
local Mark = require("mark")
local Round = require("round")
local Verdict = require("verdict")
local Experience = require("experience")
local Reward = require("reward")
local Payout = require("payout")
local Quest = require("quest")
local Order = require("order")
local Dialogue = require("dialogue")
local Notice = require("notice")
local Events = require("events")
local Docket = require("docket")

local function check(name, test)
  local ok = pcall(test)
  if ok then
    print("pass " .. name)
    return
  end
  print("fail " .. name)
end

local hero = Player.new("ash", 20, { x = 1, y = 1, z = 7 })
local foe = Creature.new("pika", "mouse", 10, { x = 1, y = 1, z = 7 })
local watch = Watch.new(hero, foe)
local battle = Battle.new(4)
local strike = Strike.new(watch, battle)
local blows = Events.new()
local mark = Mark.new(strike, blows)
local round = Round.new(mark, foe, 5)
local verdict = Verdict.new(round)
local experience = Experience.new()
local reward = Reward.new(experience, 10)
local payout = Payout.new(verdict, reward, foe)
local quest = Quest.new("clear the den", 1)
local order = Order.new(payout, quest)
local talk = Dialogue.new("clerk", { "hold the gate", "count the faint" })
local notice = Notice.new(talk, order)
local spoken = Events.new()
local docket = Docket.new(notice, spoken)

print(docket:hear())
print(spoken:count("hold the gate"))
print(order:fill())
print(docket:hear())
print(spoken:last())

check("records the closing line", function()
  local job = Quest.new("clear the den", 1)
  job:advance(1)
  local task = Order.new(payout, job)
  local speech = Dialogue.new("clerk", { "hold the gate" })
  local intro = Notice.new(speech, task)
  local board = Events.new()
  local book = Docket.new(intro, board)
  assert(book:hear() == "clerk is done")
  assert(board:count("clerk is done") == 1)
  assert(speech.step == 1)
end)
