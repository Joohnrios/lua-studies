check("stays on a gap", function()
  local mover = Player.new("ash", 20, { x = 1, y = 1, z = 7 })
  local other = Creature.new("pika", "mouse", 10, { x = 4, y = 1, z = 7 })
  local place = World.new(mover, other)
  local job = Quest.new("clear the den", 3)
  local task = Order.new(payout, job)
  local speech = Dialogue.new("clerk", { "hold the gate", "stay there" })
  local intro = Notice.new(speech, task)
  local sheet = Events.new()
  local book = Docket.new(intro, sheet)
  local seal = Stamp.new(book, "clerk")
  local entry = Gate.new(seal, mover)
  local edge = Threshold.new(entry, place)
  local roll = Visits.new(edge, place)
  local card = Permit.new(roll)
  local names = Events.new()
  local list = Roster.new(card, names)
  local here = Presence.new(list)
  local lines = Dialogue.new("clerk", { "come in" })
  local front = Welcome.new(here, lines)
  local pad = Events.new()
  local counter = Desk.new(front, pad)
  local paper = Slip.new(counter, pad)
  local voice = Echo.new(paper)
  local rung = Events.new()
  local bell = Chime.new(voice, rung)
  local ring = Peal.new(bell)
  local tone = Chord.new(ring)
  local heard = Events.new()
  local line = Phrase.new(tone, heard)
  local hook = Refrain.new(line, heard)
  local call = Cue.new(hook)
  local kept = Events.new()
  local point = Spot.new(call, kept)
  local tick = Pulse.new(point)
  local bar = Meter.new(tick)
  local staff = Events.new()
  local sign = Clef.new(bar, staff)
  local step = March.new(sign, mover)
  local path = Events.new()
  local track = Trail.new(step, path)
  local rate = Pace.new(track)
  local walk = Stride.new(rate)
  assert(walk:play() == "hold")
  assert(walk:play() == "hold")
  assert(rate:kept() == 0)
  assert(lines.step == 1)
  assert(mover.x == 1)
end)
